import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const packagePath = join(root, "package.json");
const packageJson = JSON.parse(readFileSync(packagePath, "utf8"));
const tscPath = join(root, "node_modules", "typescript", "bin", "tsc");

mkdirSync(join(root, "web", "engine"), { recursive: true });
execFileSync(process.execPath, [tscPath, "-p", "tsconfig.web.json"], {
  cwd: root,
  stdio: "inherit"
});

writeFileSync(
  join(root, "web", "engine", "version.js"),
  `// Generated by scripts/build-web.mjs from package.json.\nexport const VERSION = ${JSON.stringify(packageJson.version)};\n`
);

const vague = readFileSync(join(root, "examples", "support-reply.v1.md"), "utf8");
const structured = readFileSync(join(root, "examples", "support-reply.v2.md"), "utf8");
writeFileSync(
  join(root, "web", "engine", "samples.js"),
  [
    "// Generated by scripts/build-web.mjs from examples/.",
    `export const SAMPLES = {`,
    `  vague: ${JSON.stringify(vague)},`,
    `  structured: ${JSON.stringify(structured)}`,
    "};",
    ""
  ].join("\n")
);

console.log(`Built web/engine for PromptLens ${packageJson.version}.`);
